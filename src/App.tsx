// src/App.tsx — the screen router, active-time timer, hidden-tab pause, audio unlock and PWA update banner.
import { useEffect, useState } from 'react'; // React hooks
import { useGame, getState, addActiveTime, setPaused } from './engine/store'; // state
import { unlockAudio, startAmbient, applySettings } from './audio/audio'; // audio
import { registerSW } from 'virtual:pwa-register'; // service-worker helper generated by vite-plugin-pwa
import { TitleScreen, HowToPlay } from './screens/Title'; // screens…
import { CreateProfile, ProfileView } from './screens/Profile';
import { MissionMap } from './screens/MissionMap';
import { BriefingScreen, LaunchScreen } from './screens/Briefing';
import { ExploreScreen } from './screens/Explore';
import { QuizScreen, ResultsScreen, SummaryScreen } from './screens/Quiz';
import { StudyScreen } from './screens/Study';
import { RankingsScreen } from './screens/Rankings';
import { SettingsScreen } from './screens/Settings';

export default function App() { // root component
  const s = useGame(); // current state
  const [update, setUpdate] = useState<null | (() => void)>(null); // "new version available" callback

  useEffect(() => { // register the service worker once (offline app shell)
    const updateSW = registerSW({ onNeedRefresh: () => setUpdate(() => () => updateSW(true)) }); // show banner when an update is ready
  }, []); // once

  useEffect(() => { // unlock audio on the first interaction (no autoplay)
    const first = () => { const st = getState().save.settings; unlockAudio(st); startAmbient(); window.removeEventListener('pointerdown', first); window.removeEventListener('keydown', first); }; // start sound
    window.addEventListener('pointerdown', first); window.addEventListener('keydown', first); // wait for click/tap/key
    return () => { window.removeEventListener('pointerdown', first); window.removeEventListener('keydown', first); }; // cleanup
  }, []); // once

  useEffect(() => { window.scrollTo(0, 0); }, [s.screen]); // every new screen starts at the top

  useEffect(() => { applySettings(s.save.settings); document.documentElement.classList.toggle('reduced-motion', s.save.settings.reducedMotion); }, [s.save.settings]); // apply settings live

  useEffect(() => { // active play time: counts only while actually playing and visible
    const id = setInterval(() => { // every second
      const st = getState(); // fresh state
      const playing = ['explore', 'quiz', 'launch'].includes(st.screen) && !st.paused && document.visibilityState === 'visible'; // playing?
      if (playing) addActiveTime(1000); // add one second
    }, 1000);
    return () => clearInterval(id); // cleanup
  }, []); // once

  useEffect(() => { // pause when the browser tab is hidden
    const onVis = () => { if (document.visibilityState === 'hidden' && getState().screen === 'explore') setPaused(true); }; // hidden → pause menu
    document.addEventListener('visibilitychange', onVis); return () => document.removeEventListener('visibilitychange', onVis); // subscribe/cleanup
  }, []); // once

  const screens: Record<typeof s.screen, () => React.ReactElement | null> = { // screen name → component
    title: TitleScreen, create: CreateProfile, map: MissionMap, launch: LaunchScreen, briefing: BriefingScreen, explore: ExploreScreen, // gameplay flow
    quiz: QuizScreen, results: ResultsScreen, summary: SummaryScreen, study: StudyScreen, rankings: RankingsScreen, howto: HowToPlay, // more
    settings: SettingsScreen, profile: ProfileView, // more
  };
  const Current = screens[s.screen]; // pick the component
  return (
    <div className="app"> {/* root */}
      <div className="stars" aria-hidden="true" /> {/* moving star background (CSS) */}
      <Current /> {/* the active screen */}
      {update && <div className="update-banner" role="status">A new CosmoTrekk version is ready. <button className="btn small" onClick={update}>Update</button></div>} {/* clear update behaviour */}
    </div>
  );
}
